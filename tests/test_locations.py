@pytest.mark.parametrize("raw,section,state", CASES)
def test_classify(raw, section, state):
    place = classify(raw)
    assert (place.section, place.state) == (section, state)


def test_outside_places_name_their_country():
    assert classify("Hamilton, Ontario").country == "Canada"
    assert classify("Berlin, DE").country == "Germany"
    assert classify("Tbilisi, Georgia").country == "Georgia"
    assert classify("Tokyo - Japan").country == "Japan"
